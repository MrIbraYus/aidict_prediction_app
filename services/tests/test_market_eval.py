"""Per-market evaluation: settlement from real goal order, push handling, leak-free calibration, base rates."""
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd
import pytest

from aidict_engine.market_eval import SPECS, _seq_stats, evaluate


def spec(market, outcome):
    return next(s for s in SPECS if s.market == market and s.outcome == outcome)


def test_sequence_settlement():
    s = _seq_stats("HHAAA")  # 2–0 then 2–3
    assert s["home_lead2"] and s["home_lead1"] and s["away_lead1"]
    assert not s["home_never_trail"] and s["any_run3"] and s["home_run2"] and not s["home_run3"]
    assert s["first_home"] and not s["first_away"]


def test_path_markets_settle_from_real_order_not_final_score():
    two_up = spec("1x2-2up", "home")
    assert two_up.settle(2, 3, "HHAAA") == 1.0  # led by two, then lost: 2UP still wins
    assert two_up.settle(2, 3, "HAHAA") == 0.0  # same final score, never two up
    assert two_up.settle(2, 3, None) is None  # no sequence → excluded, never guessed
    assert spec("first-goal", "home").settle(0, 0, "") == 0.0


def test_draw_no_bet_excludes_pushes():
    dnb = spec("asian-handicap", "home0")
    assert dnb.settle(1, 1, None) is None and dnb.settle(2, 1, None) == 1.0 and dnb.settle(0, 1, None) == 0.0


def test_combined_markets_settle_as_joint_events():
    hov = spec("home-or-over25", "yes")
    assert hov.settle(1, 0, None) == 1.0 and hov.settle(1, 2, None) == 1.0 and hov.settle(0, 1, None) == 0.0


def _frame(n_per_season=400, seasons=("2019-20", "2020-21", "2021-22"), seed=0):
    rng = np.random.default_rng(seed)
    rows = []
    t0 = datetime(2019, 8, 1, tzinfo=timezone.utc)
    for i, s in enumerate(seasons):
        for k in range(n_per_season):
            lh, la = rng.uniform(0.8, 2.2), rng.uniform(0.6, 1.8)
            gh, ga = int(rng.poisson(lh)), int(rng.poisson(la))
            seq = "".join(rng.permutation(["H"] * gh + ["A"] * ga))
            rows.append({"season": s, "kickoff": t0 + timedelta(days=365 * i + k * 0.5), "gh": gh, "ga": ga, "lam_h": lh, "lam_a": la, "rho": 0.0, "goal_seq": seq})
    return pd.DataFrame(rows)


def test_evaluate_reports_every_market_and_calibrates_out_of_fold():
    hist = _frame(seasons=("2017-18", "2018-19", "2019-20", "2020-21", "2021-22"))
    bt = hist[hist.season >= "2019-20"].reset_index(drop=True)
    res = evaluate(bt, hist)
    assert {r["market"] for r in res} >= {"ou", "btts", "dc", "handicap", "first-goal", "any-2-row", "1x2-2up", "home-or-over25"}
    ou = next(r for r in res if r["market"] == "ou" and r["outcome"] == "over2.5")
    # Data generated by the model itself → well calibrated and better than the base rate.
    assert ou["raw"]["ece"] < 0.06 and ou["raw"]["log_loss"] < ou["raw"]["base_log_loss"]
    # First test season has no earlier test season → it is never calibrated (no leakage).
    assert ou["calibrated"]["n"] == len(bt[bt.season > "2019-20"])
    path = next(r for r in res if r["market"] == "1x2-2up")
    assert path["raw"]["n"] == len(bt)


def test_missing_sequences_are_excluded_not_zero():
    hist = _frame(seasons=("2018-19", "2019-20", "2020-21"))
    hist.loc[hist.index % 2 == 0, "goal_seq"] = None
    bt = hist[hist.season >= "2019-20"].reset_index(drop=True)
    res = evaluate(bt, hist)
    fg = next(r for r in res if r["market"] == "first-goal" and r["outcome"] == "home")
    assert fg["raw"]["n"] == bt.goal_seq.notna().sum()
